package com.minamikune.billiards.physics

import com.sun.management.ThreadMXBean
import org.junit.Assert.assertTrue
import org.junit.Test
import java.lang.management.ManagementFactory

/**
 * Allocation budget for the fixed 480 Hz physics step.
 *
 * The simulation thread steps 480 times per simulated second; every temporary
 * vector it allocates shows up as garbage-collector pressure on the device.
 * This test pins the per-step allocation budget so the stage-7 hot-path
 * scalarisation (and any future refactor) cannot silently regress it.
 *
 * Budget history: pre-stage-7 vector-heavy step allocated ~17 KB/step; the
 * scalarised step must stay below 2 KB/step (10x margin below the old churn,
 * still generous enough for the event objects generated by real contacts).
 */
class PhysicsAllocationBudgetTest {

    @Test
    fun physicsStepAllocationsStayWithinBudget() {
        val bean = ManagementFactory.getThreadMXBean() as ThreadMXBean
        val world = PhysicsWorld()
        val dt = 1.0 / 480.0
        world.strikeCue(Strike(Vec2(1.0, 0.05), 8.0, sideSpin = 0.1, verticalSpin = 0.1))
        repeat(2400) { world.step(dt) } // warmup; JIT settles, rack breaks open

        val steps = 4800L
        val before = bean.getThreadAllocatedBytes(Thread.currentThread().id)
        repeat(steps.toInt()) { world.step(dt) }
        val allocated = bean.getThreadAllocatedBytes(Thread.currentThread().id) - before
        val perStep = allocated.toDouble() / steps
        println("allocated per step: %.0f bytes".format(perStep))
        assertTrue(
            "per-step allocations %.0f bytes exceed the 2048-byte budget".format(perStep),
            perStep < 2048.0,
        )
    }
}
